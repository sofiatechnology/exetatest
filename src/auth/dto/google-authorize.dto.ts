import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsIn,
  IsNotEmpty,
  IsOptional,
  IsString,
  Length,
} from 'class-validator';

export class GoogleAuthorizeDto {
  @ApiProperty({
    description:
      'Expo web URL or configured mobile app scheme. This is separate from GOOGLE_REDIRECT_URI.',
    example: 'exetatest://auth/google/callback',
  })
  @IsString()
  @IsNotEmpty()
  @Length(1, 2048)
  redirect_uri: string;

  @ApiProperty({
    description:
      'Unpredictable client-generated state returned to the frontend.',
    example: 'random-client-state-1234567890',
  })
  @IsString()
  @IsNotEmpty()
  state: string;

  @ApiPropertyOptional({
    description:
      'Must match the Google OAuth client configured for the backend.',
  })
  @IsOptional()
  @IsString()
  @IsNotEmpty()
  client_id?: string;

  @ApiPropertyOptional({ enum: ['code'], default: 'code' })
  @IsOptional()
  @IsIn(['code'])
  response_type?: 'code';

  @ApiPropertyOptional({
    description:
      'Optional Google identity scopes. Only openid, email, and profile are accepted.',
    example: 'openid email profile',
  })
  @IsOptional()
  @IsString()
  @IsNotEmpty()
  scope?: string;

  @ApiPropertyOptional({
    description: 'PKCE challenge generated by the client.',
    example: 'yG3f5PxWmVg7NtV0b4nmm4USuPzE2Hz2YINx6gpZ8tM',
  })
  @IsOptional()
  @IsString()
  @Length(43, 128)
  code_challenge?: string;

  @ApiPropertyOptional({ enum: ['S256', 'plain'] })
  @IsOptional()
  @IsIn(['S256', 'plain'])
  code_challenge_method?: 'S256' | 'plain';
}
